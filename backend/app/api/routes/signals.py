import uuid

from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy import select
from sqlalchemy.orm import Session, selectinload

from app.api.deps import get_owned_company_profile
from app.db.session import get_db
from app.models.company_profile import CompanyProfile
from app.models.enums import SignalImportance, SignalStatus, SignalUrgency
from app.models.prospect import Prospect
from app.models.signal import Signal
from app.schemas.signal import SignalRead, SignalUpdate

router = APIRouter()


def _get_prospect_or_404(db: Session, profile_id: uuid.UUID, prospect_id: uuid.UUID) -> Prospect:
    prospect = db.get(Prospect, prospect_id)
    if prospect is None or prospect.company_profile_id != profile_id:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Prospect not found")
    return prospect


@router.get(
    "/company-profiles/{company_profile_id}/prospects/{prospect_id}/signals",
    response_model=list[SignalRead],
)
def list_signals(
    prospect_id: uuid.UUID,
    status_filter: SignalStatus | None = Query(None, alias="status"),
    importance: SignalImportance | None = Query(None),
    urgency: SignalUrgency | None = Query(None),
    profile: CompanyProfile = Depends(get_owned_company_profile),
    db: Session = Depends(get_db),
) -> list[Signal]:
    _get_prospect_or_404(db, profile.id, prospect_id)
    stmt = (
        select(Signal)
        .where(Signal.prospect_id == prospect_id)
        .options(selectinload(Signal.evidence))
        .order_by(Signal.detected_at.desc())
    )
    if status_filter is not None:
        stmt = stmt.where(Signal.status == status_filter)
    if importance is not None:
        stmt = stmt.where(Signal.importance == importance)
    if urgency is not None:
        stmt = stmt.where(Signal.urgency == urgency)
    return list(db.scalars(stmt).all())


def _get_signal_or_404(db: Session, prospect_id: uuid.UUID, signal_id: uuid.UUID) -> Signal:
    stmt = select(Signal).where(Signal.id == signal_id).options(selectinload(Signal.evidence))
    signal = db.scalars(stmt).first()
    if signal is None or signal.prospect_id != prospect_id:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Signal not found")
    return signal


@router.get(
    "/company-profiles/{company_profile_id}/prospects/{prospect_id}/signals/{signal_id}",
    response_model=SignalRead,
)
def get_signal(
    prospect_id: uuid.UUID,
    signal_id: uuid.UUID,
    profile: CompanyProfile = Depends(get_owned_company_profile),
    db: Session = Depends(get_db),
) -> Signal:
    _get_prospect_or_404(db, profile.id, prospect_id)
    return _get_signal_or_404(db, prospect_id, signal_id)


@router.put(
    "/company-profiles/{company_profile_id}/prospects/{prospect_id}/signals/{signal_id}",
    response_model=SignalRead,
)
def update_signal(
    prospect_id: uuid.UUID,
    signal_id: uuid.UUID,
    signal_in: SignalUpdate,
    profile: CompanyProfile = Depends(get_owned_company_profile),
    db: Session = Depends(get_db),
) -> Signal:
    """A rep can only move a Signal's status (reviewed/dismissed) - every
    other field is system-generated by the AI Analysis Engine and stays
    read-only here."""
    _get_prospect_or_404(db, profile.id, prospect_id)
    signal = _get_signal_or_404(db, prospect_id, signal_id)
    signal.status = signal_in.status
    db.commit()
    db.refresh(signal)
    return signal

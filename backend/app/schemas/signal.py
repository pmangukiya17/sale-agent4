import uuid
from datetime import datetime

from pydantic import BaseModel, ConfigDict

from app.models.enums import SignalImportance, SignalStatus, SignalUrgency


class SignalEvidenceRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    signal_id: uuid.UUID
    raw_document_id: uuid.UUID
    ai_analysis_id: uuid.UUID | None
    excerpt: str | None


class SignalUpdate(BaseModel):
    """A rep can only move a Signal's status (reviewed/dismissed) - every
    other field is system-generated by the AI Analysis Engine."""

    status: SignalStatus


class SignalRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    prospect_id: uuid.UUID
    intelligence_snapshot_id: uuid.UUID | None
    signal_type: str
    title: str
    description: str | None
    detected_at: datetime
    confidence: float | None
    reasoning: str | None
    importance: SignalImportance
    urgency: SignalUrgency
    status: SignalStatus
    evidence: list[SignalEvidenceRead] = []
    created_at: datetime
    updated_at: datetime

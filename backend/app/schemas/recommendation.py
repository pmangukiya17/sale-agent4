import uuid
from datetime import datetime

from pydantic import BaseModel, ConfigDict

from app.models.enums import RecommendationStatus, RecommendationType


class RecommendationEvidenceRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    recommendation_id: uuid.UUID
    raw_document_id: uuid.UUID
    ai_analysis_id: uuid.UUID | None
    excerpt: str | None


class RecommendationUpdate(BaseModel):
    """A rep can only move a Recommendation's status (accepted/dismissed) -
    every other field is system-generated by the AI Analysis Engine."""

    status: RecommendationStatus


class RecommendationRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    prospect_id: uuid.UUID
    intelligence_snapshot_id: uuid.UUID | None
    recommendation_type: RecommendationType
    product_id: uuid.UUID | None
    title: str
    rationale: str | None
    confidence: float | None
    reasoning: str | None
    status: RecommendationStatus
    evidence: list[RecommendationEvidenceRead] = []
    created_at: datetime
    updated_at: datetime
